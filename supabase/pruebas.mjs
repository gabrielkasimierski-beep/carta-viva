async function falla(sql, p, esperado) {
  try { await db.query(sql, p); } catch (e) { assert.match(e.message, new RegExp(esperado)); console.log("  ✓ rechaza:", esperado); return; }
  throw new Error("Tenía que fallar con " + esperado + ": " + sql);
}

